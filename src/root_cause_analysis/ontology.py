# ABox materialisation
# ---------------------------------------------------------------------------


def _asset_uri(asset_id: str) -> URIRef:
    return ONTO[str(asset_id).replace(" ", "_")]


def materialize_assets(g: Graph, measurements: pd.DataFrame, asset_column: str = "Asset") -> Graph:
    """Add asset and measurement individuals from a measurements table."""
    df = measurements.copy()
    if asset_column not in df.columns:
        df[asset_column] = [f"PW{101 + i}" for i in range(len(df))]

    for _, row in df.iterrows():
        asset_id = str(row[asset_column])
        asset = _asset_uri(asset_id)
        g.add((asset, RDF.type, ONTO.Transformer))
        g.add((asset, RDFS.label, Literal(asset_id)))
        for column, value in row.items():
            if column == asset_column or pd.isna(value):
                continue
            prop_name = str(column).replace(" ", "_")
            meas = ONTO[f"{asset_id}_{prop_name}"]
            is_gas = column in GAS_COLUMN_ALIASES and column not in {"CO", "CO2", "O2"}
            meas_class = (
                ONTO.DGAMeasurement
                if column in GAS_COLUMN_ALIASES
                else (ONTO.OilQualityMeasurement)
            )
            g.add((meas, RDF.type, meas_class))
            g.add((asset, ONTO.hasMeasurement, meas))
            g.add((meas, ONTO.observedProperty, ONTO[prop_name]))
            g.add((meas, ONTO.hasValue, Literal(float(value), datatype=XSD.double)))
            unit = PARAMETER_UNITS.get(str(column))
            if unit:
                g.add((meas, ONTO.hasUnit, Literal(unit)))
            # Backward-compatible water level triple.
            if column == "Water content":
                g.add((asset, ONTO.relatesToWaterContent, meas))
                g.add((meas, ONTO.hasWaterLevel, Literal(float(value), datatype=XSD.double)))
            _ = is_gas
    return g


def row_to_gas_dict(row: Mapping[str, float]) -> dict[str, float]:
    """Translate a friendly measurement row into gas-symbol keys (H2, CH4, ...)."""
    gases: dict[str, float] = {}
    for column, symbol in GAS_COLUMN_ALIASES.items():
        if column in row and not pd.isna(row[column]):
            gases[symbol] = float(row[column])
    return gases


def build_knowledge_graph(measurements: pd.DataFrame) -> Graph:
    """Build a knowledge graph: TBox schema + materialised asset measurements."""
    g = build_tbox()
    materialize_assets(g, measurements)
    return g


def serialize_ontology(output_dir: str | Path) -> dict[str, Path]:
    """Serialize the TBox to Turtle and RDF/XML; return the written paths."""
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)
    g = build_tbox()
    ttl = out / "onto_pw.ttl"
    owl = out / "onto_pw.owl"
    g.serialize(destination=ttl, format="turtle")
    g.serialize(destination=owl, format="pretty-xml")
    return {"ttl": ttl, "owl": owl}


def iter_class_descriptions(g: Graph | None = None) -> Iterable[tuple[str, str]]:
    """Yield ``(label, comment)`` for every described class (documentation aid)."""
    graph = g if g is not None else build_tbox()
    for cls in graph.subjects(RDF.type, OWL.Class):
        label = graph.value(cls, RDFS.label)
        comment = graph.value(cls, RDFS.comment)
        if label is not None and comment is not None:
            yield (str(label), str(comment))
